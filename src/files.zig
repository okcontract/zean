const std = @import("std");
const builtin = @import("builtin");
const c = @import("common.zig");
const Dir = std.Io.Dir;
const File = std.Io.File;

pub const generated_lean_header = "-- Autogenerated by Zean. Do not edit.\n";

pub fn readJson(ctx: *c.Context, io: std.Io, path: []const u8) !struct { bytes: []const u8, value: c.Value } {
    const bytes = try ctx.read(io, path, c.max_json_bytes + 1);
    return .{ .bytes = bytes, .value = try ctx.parse(bytes) };
}
pub fn exists(io: std.Io, path: []const u8) !bool {
    _ = std.Io.Dir.cwd().statFile(io, path, .{ .follow_symlinks = false }) catch |err| switch (err) {
        error.FileNotFound => return false,
        else => return err,
    };
    return true;
}
pub fn regular(ctx: *c.Context, io: std.Io, path: []const u8) !void {
    const stat = try std.Io.Dir.cwd().statFile(io, path, .{ .follow_symlinks = false });
    try ctx.require(stat.kind == .file, "captured AIR must be a regular file");
}
/// Resolve an explicit closure member without following any relative symlink.
/// The caller chooses the trusted base directory; every member component is
/// normalized and checked before the file is read.
pub fn closureMember(ctx: *c.Context, io: std.Io, base: []const u8, relative: []const u8) ![]const u8 {
    try ctx.require(@import("runtime.zig").safeArchiveName(relative), "invalid captured source path");
    var parts = std.mem.splitScalar(u8, relative, '/');
    var path = base;
    while (parts.next()) |part| {
        try ctx.require(part.len > 0 and !std.mem.eql(u8, part, "."), "captured source path must be normalized");
        path = try join(ctx, &.{ path, part });
        const stat = try std.Io.Dir.cwd().statFile(io, path, .{ .follow_symlinks = false });
        try ctx.require(if (parts.peek() == null) stat.kind == .file else stat.kind == .directory, "captured source path contains a link or special file");
    }
    return path;
}
pub fn write(io: std.Io, path: []const u8, bytes: []const u8) !void {
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = path, .data = bytes });
}
pub fn join(ctx: *c.Context, parts: []const []const u8) ![]const u8 {
    return std.fs.path.join(ctx.allocator, parts);
}

pub fn absolute(ctx: *c.Context, io: std.Io, path: []const u8) ![]const u8 {
    if (Dir.path.isAbsolute(path)) return Dir.path.resolve(ctx.allocator, &.{path});
    const cwd = try std.process.currentPathAlloc(io, ctx.allocator);
    defer ctx.allocator.free(cwd);
    return Dir.path.resolve(ctx.allocator, &.{ cwd, path });
}

pub fn validRelativePath(path: []const u8) bool {
    if (!@import("runtime.zig").safeArchiveName(path) or std.mem.indexOfScalar(u8, path, 0) != null) return false;
    var parts = std.mem.splitScalar(u8, path, '/');
    while (parts.next()) |part| {
        if (part.len == 0 or std.mem.eql(u8, part, ".")) return false;
    }
    return true;
}

/// Compare normalized path components by spelling.
pub fn within(root: []const u8, path: []const u8) bool {
    return std.mem.startsWith(u8, path, root) and
        (path.len == root.len or std.mem.endsWith(u8, root, "/") or path[root.len] == '/');
}

/// Some kernels report NotDir for a symlink opened with O_NOFOLLOW.
pub fn openChildDir(io: std.Io, parent: Dir, component: []const u8) !Dir {
    return parent.openDir(io, component, .{ .follow_symlinks = false }) catch |err| {
        if (err == error.NotDir and (try parent.statFile(io, component, .{ .follow_symlinks = false })).kind == .sym_link)
            return error.SymLinkLoop;
        return err;
    };
}

/// Open the parent of a validated, normalized relative path without following links.
pub fn openParent(io: std.Io, root: Dir, path: []const u8, create: bool) !Dir {
    var dir = try root.openDir(io, ".", .{});
    errdefer dir.close(io);
    var parts = std.mem.splitScalar(u8, path, '/');
    while (parts.next()) |part| {
        if (parts.peek() == null) break;
        const child = openChildDir(io, dir, part) catch |err| blk: {
            if (err != error.FileNotFound or !create) return err;
            dir.createDir(io, part, .default_dir) catch |create_err| {
                if (create_err != error.PathAlreadyExists) return create_err;
            };
            break :blk try openChildDir(io, dir, part);
        };
        dir.close(io);
        dir = child;
    }
    return dir;
}

pub fn openRegular(io: std.Io, dir: Dir, name: []const u8, lock: std.Io.File.Lock) !std.Io.File {
    if ((try dir.statFile(io, name, .{ .follow_symlinks = false })).kind != .file) return error.NotRegularFile;
    const file = try dir.openFile(io, name, .{
        .allow_directory = false,
        .follow_symlinks = false,
        .lock = lock,
        .lock_nonblocking = lock != .none,
    });
    errdefer file.close(io);
    if ((try file.stat(io)).kind != .file) return error.NotRegularFile;
    return file;
}

pub fn openContained(io: std.Io, root: Dir, path: []const u8) !File {
    const parent = try openParent(io, root, path, false);
    defer parent.close(io);
    return openRegular(io, parent, Dir.path.basenamePosix(path), .none);
}

pub fn readContained(ctx: *c.Context, io: std.Io, root: Dir, path: []const u8) ![]const u8 {
    const file = try openContained(io, root, path);
    defer file.close(io);
    return readFile(ctx, io, file);
}

/// Borrow a directory descriptor for file identity checks and locks.
pub fn directoryFile(dir: Dir) File {
    return .{ .handle = dir.handle, .flags = .{ .nonblocking = false } };
}

pub const Identity = struct {
    device: u64,
    inode: u64,

    pub fn of(file: File, io: std.Io) !Identity {
        // Io.File.Stat exposes the inode, but not the device it belongs to.
        switch (builtin.target.os.tag) {
            .linux => {
                const linux = std.os.linux;
                var stat: linux.Statx = undefined;
                while (true) {
                    switch (linux.errno(linux.statx(file.handle, "", linux.AT.EMPTY_PATH, .{ .INO = true }, &stat))) {
                        .SUCCESS => break,
                        .INTR => continue,
                        else => |err| return std.posix.unexpectedErrno(err),
                    }
                }
                if (!stat.mask.INO) return error.FileIdentityUnavailable;
                return .{ .device = (@as(u64, stat.dev_major) << 32) | stat.dev_minor, .inode = stat.ino };
            },
            .macos => {
                var stat: std.c.Stat = undefined;
                while (true) {
                    switch (std.posix.errno(std.c.fstat(file.handle, &stat))) {
                        .SUCCESS => break,
                        .INTR => continue,
                        else => |err| return std.posix.unexpectedErrno(err),
                    }
                }
                return .{ .device = @as(u32, @bitCast(stat.dev)), .inode = stat.ino };
            },
            else => return .{ .device = 0, .inode = (try file.stat(io)).inode },
        }
    }
};

pub fn readFile(ctx: *c.Context, io: std.Io, file: std.Io.File) ![]const u8 {
    var buffer: [4096]u8 = undefined;
    var reader = file.reader(io, &buffer);
    return reader.interface.allocRemaining(ctx.allocator, .limited(c.max_json_bytes));
}

pub const Artifact = struct { name: []const u8, bytes: []const u8 };

pub fn publish(ctx: *c.Context, io: std.Io, output: []const u8, artifacts: []const Artifact) !void {
    try ctx.require(!try exists(io, output), "output directory already exists; use a new directory");
    const parent = std.fs.path.dirname(output) orelse ".";
    try std.Io.Dir.cwd().createDirPath(io, parent);
    var nonce: [16]u8 = undefined;
    io.random(&nonce);
    const staging = try join(ctx, &.{ parent, try ctx.fmt(".zean-{s}", .{std.fmt.bytesToHex(nonce, .lower)}) });
    try std.Io.Dir.cwd().createDir(io, staging, .default_dir);
    defer std.Io.Dir.cwd().deleteTree(io, staging) catch {};
    for (artifacts) |artifact| {
        const dot = std.mem.lastIndexOfScalar(u8, artifact.name, '.') orelse return ctx.fail("artifact needs a Lean or JSON extension", .{});
        try ctx.require(c.identifier(artifact.name[0..dot], false) and c.oneOf(artifact.name[dot..], &.{ ".lean", ".json" }), "invalid artifact name");
        try write(io, try join(ctx, &.{ staging, artifact.name }), artifact.bytes);
    }
    try std.Io.Dir.renamePreserve(.cwd(), staging, .cwd(), output, io);
}
